// POST /api/box-sets/:id/components/sync - Persist auto-generated components to database
export async function syncBoxSetComponents(req: Request, res: Response): Promise<void> {
  try {
    const { id } = req.params;
    const rawId = id.replace(/^boxset-/, '');

    const boxSet = await prisma.boxSet.findUnique({
      where: { id: rawId },
    });

    if (!boxSet) {
      res.status(404).json({ error: 'Box set not found' });
      return;
    }

    // Generate components from flags
    const autoGenerated = generateComponentsFromFlags(boxSet);

    // Delete existing auto-generated components
    await prisma.boxSetComponent.deleteMany({
      where: {
        boxSetId: rawId,
        isAutoGenerated: true,
      },
    });

    // Insert new auto-generated components
    const components = await prisma.boxSetComponent.createMany({
      data: autoGenerated.map((c, index) => ({
        boxSetId: rawId,
        type: c.type,
        name: c.name,
        required: c.required,
        count: c.count,
        position: index,
        isAutoGenerated: true,
      })),
    });

    res.json({
      success: true,
      synced: components.count,
      message: `Synced ${components.count} auto-generated components`,
    });
  } catch (err) {
    console.error('Failed to sync components:', err);
    res.status(500).json({ error: 'Failed to sync components' });
  }
}
