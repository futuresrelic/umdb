// GET /api/box-sets/:id/components - Get all components (auto-generated + manual)
export async function getBoxSetComponents(req: Request, res: Response): Promise<void> {
  try {
    const { id } = req.params;
    const rawId = id.replace(/^boxset-/, '');

    const boxSet = await prisma.boxSet.findUnique({
      where: { id: rawId },
      include: {
        components: {
          orderBy: { position: 'asc' },
        },
      },
    });

    if (!boxSet) {
      res.status(404).json({ error: 'Box set not found' });
      return;
    }

    // Get auto-generated components
    const autoGenerated = generateComponentsFromFlags(boxSet);

    // Get manual components from database
    const manualComponents = boxSet.components.map(c => ({
      id: c.id,
      type: c.type,
      name: c.name,
      required: c.required,
      count: c.count,
      position: c.position,
      isAutoGenerated: c.isAutoGenerated,
    }));

    res.json({
      components: {
        autoGenerated,
        manual: manualComponents,
        all: [...autoGenerated, ...manualComponents],
      },
    });
  } catch (err) {
    console.error('Failed to get components:', err);
    res.status(500).json({ error: 'Failed to get components' });
  }
}

