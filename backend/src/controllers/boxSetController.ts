import { Request, Response } from 'express';
import { PrismaClient, EntryStatus } from '@prisma/client';

const prisma = new PrismaClient();

// Component type definition
interface Component {
  type: string;
  name: string;
  required: boolean;
  count?: number;
}

// Helper function to auto-generate components from box set flags
function generateComponentsFromFlags(boxSet: any): Component[] {
  const components: Component[] = [];

  // Slipcover
  if (boxSet.hasSlipcover) {
    components.push({
      type: 'slipcover',
      name: 'Slipcover',
      required: true,
    });
  }

  // Booklet
  if (boxSet.hasBooklet) {
    components.push({
      type: 'booklet',
      name: 'Booklet',
      required: true,
    });
  }

  // Bonus discs
  if (boxSet.hasBonusDisc) {
    const count = boxSet.bonusDiscCount || 1;
    for (let i = 1; i <= count; i++) {
      components.push({
        type: 'disc',
        name: count > 1 ? `Bonus Disc ${i}` : 'Bonus Disc',
        required: true,
      });
    }
  }

  // Digital copy
  if (boxSet.hasDigitalCopy) {
    components.push({
      type: 'digital_code',
      name: 'Digital Copy Code',
      required: true,
    });
  }

  // 3D discs (if applicable)
  if (boxSet.has3d) {
    components.push({
      type: 'disc',
      name: '3D Disc',
      required: true,
    });
  }

  // Package type based components
  if (boxSet.packageType) {
    const pkgType = boxSet.packageType.toLowerCase();
    if (pkgType.includes('slipcase')) {
      components.push({
        type: 'outer_case',
        name: 'Slipcase',
        required: true,
      });
    } else if (pkgType.includes('digipak')) {
      components.push({
        type: 'case',
        name: 'Digipak',
        required: true,
      });
    } else if (pkgType.includes('steelbook')) {
      components.push({
        type: 'case',
        name: 'Steelbook',
        required: true,
      });
    }
  }

  // Edition-based components
  if (boxSet.edition) {
    const editionLower = boxSet.edition.toLowerCase();
    if (editionLower.includes('criterion')) {
      components.push({
        type: 'booklet',
        name: 'Criterion Booklet',
        required: true,
      });
    }
    if (editionLower.includes('poster')) {
      components.push({
        type: 'poster',
        name: 'Poster',
        required: true,
      });
    }
    if (editionLower.includes('art cards') || editionLower.includes('postcards')) {
      components.push({
        type: 'art_cards',
        name: 'Art Cards',
        required: true,
      });
    }
  }

  return components;
}

// GET /api/box-sets - List all box sets with search and pagination
export async function getAllBoxSets(req: Request, res: Response): Promise<void> {
  try {
    const { search, format, sortBy = 'createdAt', sortOrder = 'desc', limit = 50, offset = 0 } = req.query;

    const where: any = {};

    // Search by name or notes
    if (search) {
      where.OR = [
        { name: { contains: search as string, mode: 'insensitive' } },
        { notes: { contains: search as string, mode: 'insensitive' } },
      ];
    }

    // Filter by format
    if (format) {
      where.format = format;
    }

    const [boxSets, total] = await Promise.all([
      prisma.boxSet.findMany({
        where,
        include: {
          items: {
            include: {
              movie: {
                select: {
                  id: true,
                  title: true,
                  year: true,
                  posterUrl: true,
                },
              },
            },
            orderBy: { position: 'asc' },
          },
          releases: {
            select: { id: true },
          },
        },
        orderBy: { [sortBy as string]: sortOrder },
        take: Number(limit),
        skip: Number(offset),
      }),
      prisma.boxSet.count({ where }),
    ]);

    // Format response
    const formattedBoxSets = boxSets.map(boxSet => {
      const autoGeneratedComponents = generateComponentsFromFlags(boxSet);

      return {
        id: `boxset-${boxSet.id}`,
        name: boxSet.name,
        format: boxSet.format,
        region: boxSet.region,
        edition: boxSet.edition,
        packageType: boxSet.packageType,
        coverImageUrl: boxSet.coverImageUrl,
        spineImageUrl: boxSet.spineImageUrl,
        movieCount: boxSet.items.length,
        releaseCount: boxSet.releases?.length || 0,
        components: autoGeneratedComponents,
        createdAt: boxSet.createdAt,
        movies: boxSet.items.map(item => ({
          id: item.movie?.id ? `movie-${item.movie.id}` : null,
          title: item.movie?.title,
          year: item.movie?.year,
          posterUrl: item.movie?.posterUrl,
          position: item.position,
          discNumber: item.discNumber,
          discLabel: item.discLabel,
          isPresent: item.isPresent,
        })),
      };
    });

    res.json({
      boxSets: formattedBoxSets,
      total,
      limit: Number(limit),
      offset: Number(offset),
    });
  } catch (err) {
    console.error('Failed to get box sets:', err);
    res.status(500).json({ error: 'Failed to get box sets' });
  }
}

// GET /api/box-sets/:id - Get a single box set with all details
export async function getBoxSet(req: Request, res: Response): Promise<void> {
  try {
    const { id } = req.params;
    const rawId = id.replace(/^boxset-/, '');

    const boxSet = await prisma.boxSet.findUnique({
      where: { id: rawId },
      include: {
        items: {
          include: {
            movie: {
              select: {
                id: true,
                title: true,
                year: true,
                posterUrl: true,
                backdropUrl: true,
                tagline: true,
                plot: true,
                rating: true,
                runtime: true,
              },
            },
            physicalCopy: {
              select: {
                id: true,
              },
            },
          },
          orderBy: { position: 'asc' },
        },
        releases: {
          select: { id: true, movieId: true },
        },
      },
    });

    if (!boxSet) {
      res.status(404).json({ error: 'Box set not found' });
      return;
    }

    // Auto-generate components from flags
    const autoGeneratedComponents = generateComponentsFromFlags(boxSet);

    // Format response
    const formatted = {
      id: `boxset-${boxSet.id}`,
      name: boxSet.name,
      format: boxSet.format,
      region: boxSet.region,
      edition: boxSet.edition,
      packageType: boxSet.packageType,
      notes: boxSet.notes,
      coverImageUrl: boxSet.coverImageUrl,
      spineImageUrl: boxSet.spineImageUrl,
      hasSlipcover: boxSet.hasSlipcover,
      hasBooklet: boxSet.hasBooklet,
      hasBonusDisc: boxSet.hasBonusDisc,
      bonusDiscCount: boxSet.bonusDiscCount,
      hasDigitalCopy: boxSet.hasDigitalCopy,
      has3d: boxSet.has3d,
      components: autoGeneratedComponents,
      createdAt: boxSet.createdAt,
      updatedAt: boxSet.updatedAt,
      movies: boxSet.items.map(item => ({
        id: item.movie?.id ? `movie-${item.movie.id}` : null,
        boxSetItemId: item.id,
        title: item.movie?.title,
        year: item.movie?.year,
        posterUrl: item.movie?.posterUrl,
        backdropUrl: item.movie?.backdropUrl,
        plot: item.movie?.plot,
        rating: item.movie?.rating,
        runtime: item.movie?.runtime,
        position: item.position,
        discNumber: item.discNumber,
        discLabel: item.discLabel,
        isPresent: item.isPresent,
        physicalCopyId: item.physicalCopy?.id ? `rel-${item.physicalCopy.id}` : null,
      })),
      releases: boxSet.releases?.map(r => ({
        id: `rel-${r.id}`,
        movieId: r.movieId ? `movie-${r.movieId}` : null,
      })) || [],
    };

    res.json({ boxSet: formatted });
  } catch (err) {
    console.error('Failed to get box set:', err);
    res.status(500).json({ error: 'Failed to get box set' });
  }
}

// POST /api/box-sets - Create a new box set (simplified from CineShelf version)
export async function createBoxSet(req: Request, res: Response): Promise<void> {
  try {
    const {
      name,
      format,
      region,
      edition,
      packageType,
      notes,
      coverImageUrl,
      spineImageUrl,
      hasSlipcover,
      hasBooklet,
      hasBonusDisc,
      bonusDiscCount,
      hasDigitalCopy,
      has3d,
    } = req.body;

    if (!name) {
      res.status(400).json({ error: 'Name is required' });
      return;
    }

    const boxSet = await prisma.boxSet.create({
      data: {
        name,
        format: format || null,
        region: region || null,
        edition: edition || null,
        packageType: packageType || null,
        notes: notes || null,
        coverImageUrl: coverImageUrl || null,
        spineImageUrl: spineImageUrl || null,
        hasSlipcover: hasSlipcover ?? false,
        hasBooklet: hasBooklet ?? false,
        hasBonusDisc: hasBonusDisc ?? false,
        bonusDiscCount: bonusDiscCount || null,
        hasDigitalCopy: hasDigitalCopy ?? false,
        has3d: has3d ?? false,
        status: EntryStatus.VERIFIED,
      },
    });

    res.status(201).json({
      boxSet: {
        id: `boxset-${boxSet.id}`,
        name: boxSet.name,
        format: boxSet.format,
      },
    });
  } catch (err) {
    console.error('Failed to create box set:', err);
    res.status(500).json({ error: 'Failed to create box set' });
  }
}

